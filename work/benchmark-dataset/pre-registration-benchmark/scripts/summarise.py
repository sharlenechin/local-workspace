"""Generate cleaning-context/<deal>/cleaned_summary.md from the cleaned output.

    uv run python work/benchmark-dataset/pre-registration-benchmark/summarise.py PT15018

GENERATED -- do not hand-edit. It is regenerated from accounts/<deal>.parquet and
the raw tape every time, so it cannot drift from what the pipeline actually
produced. The hand-written judgement calls live beside it in CONTEXT.md.
"""
import sys
from pathlib import Path
import pandas as pd
from style import in_scope, attr_series

sys.path.insert(0, str(Path(__file__).resolve().parent))
from style import ascii_only

import paths as _P

HERE = Path(__file__).resolve().parent          # scripts/
BASE = HERE.parent                              # pre-registration-benchmark/
TAPES = _P.TAPES


def main(deal):
    acc = pd.read_parquet(_P.ACCOUNTS / f"{deal}.parquet")
    man = pd.read_parquet(TAPES / "manifest.parquet")
    man = man[man.deal == deal]
    pay = pd.read_parquet(TAPES / "payments.parquet")
    pay = pay[pay.deal == deal].copy()
    pay["amt"] = pd.to_numeric(pay.amount, errors="coerce")
    m = pd.read_csv(_P.REGISTRY).query("deal_id == @deal")
    ins = in_scope(acc)

    import json as _sj
    _mf = _P.ACCOUNTS / f"{deal}.meta.json"
    _mm = _sj.loads(_mf.read_text()) if _mf.exists() else {}

    L = [f"# {deal} -- cleaned summary", "",
         "GENERATED by `summarise.py`. Do not hand-edit -- the judgement calls are",
         "in `CONTEXT.md` beside this file.", "",
         f"    generated   {pd.Timestamp.now():%Y-%m-%d}",
         f"    source      portugal/raw/tapes/{deal}.parquet",
         f"    output      accounts/{deal}.parquet", "",
         (f"    seller      {_mm['seller']} ({_mm.get('country', '')})"
          if _mm.get("seller") else ""), "",
         "## Input", "",
         f"| | |", "|---|---:|",
         f"| Files read | {man.file.nunique()} |",
         f"| Sheets read | {len(man)} |",
         f"| Sheets that failed | {int(man.error.notna().sum())} |", ""]

    L += ["## Output -- one row per loan", "", "| | |", "|---|---:|",
          f"| Loans | {len(acc):,} |"]
    if "segment" in acc:
        L.append(f"| **In scope** (segment != Excluded) | **{len(ins):,}** |")
        L.append(f"| Out of scope | {len(acc) - len(ins):,} |")
    if "cutoff_balance" in acc:
        L.append(f"| **In-scope balance** | **EUR {ins.cutoff_balance.sum():,.2f}** |")
    if "detail_level" in acc:
        L.append(f"| Full detail | {int((acc.detail_level == 'full').sum()):,} |")
        L.append(f"| Basic | {int((acc.detail_level == 'basic').sum()):,} |")
    if "loan_id_missing_flag" in acc:
        n = int(acc.loan_id_missing_flag.fillna(False).sum())
        L.append(f"| !! No account number in the tape | {n:,} |")
    L.append("")

    # !! REPORT THE CLEANED PAYMENTS, NOT THE RAW CELLS. This counted raw
    #   cells from the tape - 854,713 for PT15018 - against a cleaned file
    #   holding 4,053 actual payments, and a total that still included money
    #   belonging to loans outside the book. A summary beside an approval
    #   sheet has to describe the file that was built.
    _pq = _P.PAYMENTS / f"{deal}.parquet"
    _pmj = _P.PAYMENTS / f"{deal}.meta.json"
    _pm = _sj.loads(_pmj.read_text()) if _pmj.exists() else {}
    if _pq.exists():
        cp = pd.read_parquet(_pq)
        grain = _pm.get("grain", "loan_id")
        L += ["## Payments", "",
              f"Cleaned to one row per {grain} x month, keeping only months "
              "where a payment",
              f"actually occurred - {_pm.get('zero_rows_dropped', 0):,} empty "
              f"cell(s) dropped (T34).", "",
              "| | |", "|---|---:|",
              f"| Payments kept | {len(cp):,} |",
              # !! COMPARE LIKE WITH LIKE. This read "1,706 of 32,529 in
              #   scope" where 1,706 is CLIENTS and 32,529 is LOANS - two
              #   different units in one ratio, which reads as 5% coverage
              #   when the real figure is 1,706 of 17,944 clients.
              f"| {grain}s with a payment | {cp[grain].nunique():,} of "
              f"{ins[grain].nunique():,} in scope |",
              f"| Months covered | {_pm.get('months_covered', 0)} |",
              f"| Gross | EUR {_pm.get('gross_pay', 0):,.2f} |",
              f"| Returns | EUR {_pm.get('returns', 0):,.2f} |",
              f"| **Net collections** | **EUR {_pm.get('net_collections', 0):,.2f}** |"]
        if _pm.get("straddling_keys"):
            L.append(f"| !! | {_pm['straddling_keys']} key(s) hold BOTH in- "
                     f"and out-of-scope loans, EUR "
                     f"{_pm.get('straddling_amount', 0):,.2f} -- kept in full |")
        if not _pm.get("netted"):
            L.append("| | no RETURNS series on this tape, so net == gross |")
        if not _pm.get("dated"):
            L.append("| !! | NO DATES on any row (T20) - cannot be placed on "
                     "a timeline |")
        L.append("")
    elif _pm.get("blocked"):
        L += ["## Payments", "",
              f"!! **Not tied to the population.** {_pm['blocked']}", "",
              "The tape carries payment columns but nothing joins them to the "
              "cleaned loans,", "so no payments file was written. The accounts "
              "are unaffected.", ""]
    else:
        L += ["## Payments", "", "This tape carries no payment columns.", ""]

    # !! ONE PAYMENTS SECTION, NOT TWO. The raw cells were a second table
    #   under their own heading, repeating the total and the month range the
    #   cleaned table had already given - so the same figure appeared twice
    #   on one page and a reader had to work out whether they disagreed.
    #   Folded in as the "what it came from" rows of the same table, which is
    #   the only thing the raw view told anybody that the cleaned one did not.
    if len(pay):
        _raw = [f"| _raw cells on the tape_ | {len(pay):,} |",
                f"| _of which carried money_ | "
                f"{int((pay.amt.fillna(0) != 0).sum()):,} |"]
        if pay.period_month.notna().any():
            _raw.append(f"| _months the tape spans_ | "
                        f"{pay.period_month.min()} .. {pay.period_month.max()} |")
        if "series" in pay and pay.series.nunique() > 1:
            for k, v in pay.groupby("series").amt.sum().items():
                _raw.append(f"| _seller's series_ `{k}` | EUR {v:,.2f} |")
        # slot them into the table that is already open, above its blank line
        for _i in range(len(L) - 1, -1, -1):
            if L[_i].startswith("|"):
                L[_i + 1:_i + 1] = _raw
                break

    # !! A TOTAL WITH NO DATES IS NOT A COLLECTIONS FIGURE (T20). PT18019 heads
    #   its payment columns -12M..-1M and 1M..3M, relative to a cut-off the tape
    #   never states. The rows are real money and the arithmetic is fine, but
    #   nothing can be placed on a timeline, compared to another deal, or cut by
    #   period. Printed as a bare total it reads exactly like PT15018's dated
    #   collections, which is the mistake this block exists to prevent.
    if len(pay) and pay.period_month.nunique() == 0:
        per = sorted(pay.period.dropna().astype(str).unique(),
                     key=lambda x: (len(x), x))
        pre = [x for x in per if x.startswith("-")]
        post = [x for x in per if not x.startswith("-")]
        L += ["!! **These payments carry NO DATES.** The columns are relative to "
              "a cut-off", "the tape never states, so this total cannot be placed "
              "on a timeline,", "compared across deals, or cut by period. "
              "Treat it as a shape, not a figure.", "",
              f"    periods   {len(per)} relative: "
              f"{len(pre)} before the cut-off, {len(post)} after",
              f"    before    {', '.join(pre)}" if pre else "",
              f"    after     {', '.join(post)}" if post else "",
              "", "To date them, the deal owner must supply the cut-off date. "
              "Until then", "`period_month` stays NULL on every row -- deliberately, not by "
              "failure.", ""]

    # !! ONE TABLE, NOT TWO DESCRIBING THE SAME ROWS. `Column fill rates`
    #   and `Mapping registry` listed the same fields twice - once with a
    #   count, once with a source - so a reader had to hold two tables in
    #   their head to answer "where did this come from and how full is it".
    #   Merged, with an EXAMPLE value and the approval state, because this
    #   document is the permanent record of what exists: REVIEW.md carries
    #   only what is still outstanding and empties as a deal is signed.
    import yaml as _yd
    _df = _P.CONTEXT / deal / "decisions.yaml"
    _dd = (_yd.safe_load(_df.read_text(encoding="utf-8")) or {}) if _df.exists() else {}
    _appr = bool(_dd.get("approved"))
    _conf = {c["field"] for c in (_dd.get("confirmed") or [])}
    _rej = {str(r.get("field")) for r in (_dd.get("open_rejections") or [])}

    _attr_names = _mm.get("attribute_names") or []
    _where = {c: "core" for c in acc.columns}
    _where.update({c: "additional" for c in _attr_names})
    _src = {}
    for _, r in m.iterrows():
        _src.setdefault(str(r.target_field), []).append(
            (str(r.role), str(r.source_sheet), str(r.source_column),
             str(r["transform"])))

    def _eg(v):
        """One real value, so a reader can see what the column holds."""
        vv = v.dropna()
        if not len(vv):
            return ""
        x = str(vv.iloc[0])
        return (x[:26] + "...") if len(x) > 26 else x

    L += ["## Every field: where it came from, how full, what it looks like",
          "",
          f"{len(m)} registry row(s) - "
          + ", ".join(f"{k} {v}" for k, v in m.role.value_counts().items())
          + f" - producing the fixed core plus "
          f"{_mm.get('attribute_rows', 0):,} rows in `additional_attributes`.",
          "",
          "`state` is **approved** once you sign the deal, **confirmed** for a "
          "field you settled",
          "on its own, **REJECTED** while a rejection is open, and blank for "
          "anything still",
          "to read. A field with no source is one THIS pipeline derives.", "",
          "| field | lands in | from (sheet / column / transform) | filled | % | example | state |",
          "|---|---|---|---:|---:|---|---|"]
    for c in list(acc.columns) + _attr_names:
        # !! NOTHING IS HIDDEN. deal_id, grain, currency_id, country and
        #   source were skipped as "boring constants" - which made this table
        #   a selection rather than the record it claims to be, and `grain`
        #   is the one field telling a consumer how to join the three
        #   outputs. A reader asking "is everything here" must be able to
        #   answer yes.
        v = acc[c] if c in acc.columns else attr_series(BASE, deal, c)
        n = int(v.notna().sum())
        rows = _src.get(c, [])
        # !! "DERIVED" AND "NOT ON THIS TAPE" ARE DIFFERENT FACTS, and this
        #   printed the first for both. PT20008's loan_id and client_id read
        #   `derived by the pipeline` at 0% filled - which says we computed
        #   something and got nothing, when the truth is that tape carries no
        #   identifier at all and we never tried.
        _DERIVED = {"unique_key", "deal_id", "deal_type", "grain",
                    "offer_stage", "verification_status", "currency_id",
                    "country", "source", "cutoff_date", "detail_level",
                    "loan_id_missing_flag", "loan_holder_individual_flag",
                    "loan_holder_corporate_flag"}
        if rows:
            frm = "<br>".join(f"`{sh}` / `{col}` / `{tr}`"
                              for _, sh, col, tr in rows)
        elif c in _DERIVED:
            frm = "_derived by the pipeline_"
        else:
            frm = "_NOT ON THIS TAPE - nothing to map_"
        state = ("REJECTED" if c in _rej else "approved" if _appr
                 else "confirmed" if c in _conf else "")
        note = ""
        if c == "judicialised_flag":
            note = " (blank = NOT KNOWN)"
        elif c == "detail_level":
            note = (" (`full` = this loan appears on a detail sheet as well "
                    "as the main one; `basic` = the main sheet only)")
        elif c == "unique_key":
            note = " (OURS: a hash of deal + file + sheet + row. The only key on EVERY loan)"
        elif c == "loan_id":
            note = " (the SELLER's account number)"
        elif c == "client_id":
            note = " (the SELLER's borrower reference)"
        elif c == "grain":
            note = " (WHICH COLUMN JOINS the three outputs on this deal)"
        elif c in ("deal_id", "currency_id", "country", "source"):
            note = " (constant for the whole deal)"
        elif c in ("claims_balance", "insolvency_claims_balance"):
            note = " (NOT a balance owed)"
        L.append(f"| `{c}`{note} | {_where.get(c, '-')} | {frm} | {n:,} | "
                 f"{100*n/len(acc):.1f}% | {_eg(v)} | {state} |")
    L.append("")

    # the rows that shape the POPULATION carry no field of their own
    _struct = m[~m.target_field.isin(list(acc.columns) + _attr_names)]
    if len(_struct):
        L += ["**Rows that shape the population, not a field.** These decide "
              "WHICH LOANS",
              "exist and which rows count:", "",
              "| role | sheet | column | effect |", "|---|---|---|---|"]
        for _, r in _struct.iterrows():
            _n = str(r.get("note") or "").replace("|", "/")
            L.append(f"| `{r.role}` | `{r.source_sheet}` | "
                     f"`{r.source_column}` | {(_n[:110] + '...') if len(_n) > 110 else _n} |")
        L.append("")

    L += ["", "## Guards", "",
          "`uv run python guards.py " + deal + "` -- see CONTEXT.md for what each asserts",
          "and which seller-published figure it ties to."]

    out = _P.CONTEXT / deal
    out.mkdir(parents=True, exist_ok=True)
    (out / "cleaned_summary.md").write_text(ascii_only("\n".join(L) + "\n"))
    print(f"wrote cleaning-context/{deal}/cleaned_summary.md")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1] if len(sys.argv) > 1 else "PT15018"))
